// Command commands turns the Linkbreakers OpenAPI document into the CLI's
// command table, so every operation of the API is a command and none is
// written by hand.
//
//	go run ./internal/gen/commands <openapi.json> <output.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type document struct {
	Info       struct{ Version string }             `json:"info"`
	Tags       []struct{ Name, Description string } `json:"tags"`
	Paths      map[string]map[string]json.RawMessage
	Components struct {
		Schemas map[string]schema `json:"schemas"`
	} `json:"components"`
}

type schema struct {
	Ref                  string            `json:"$ref"`
	Type                 json.RawMessage   `json:"type"`
	Format               string            `json:"format"`
	Enum                 []any             `json:"enum"`
	Items                *schema           `json:"items"`
	Properties           map[string]schema `json:"properties"`
	AdditionalProperties json.RawMessage   `json:"additionalProperties"`
	Required             []string          `json:"required"`
	Title                string            `json:"title"`
	Description          string            `json:"description"`
	AllOf                []schema          `json:"allOf"`
}

type operationDoc struct {
	OperationID string       `json:"operationId"`
	Summary     string       `json:"summary"`
	Description string       `json:"description"`
	Parameters  []parameter  `json:"parameters"`
	Security    []any        `json:"security"`
	RequestBody *requestBody `json:"requestBody"`
	Deprecated  bool         `json:"deprecated"`
	Tags        []string     `json:"tags"`
}

type parameter struct {
	Name        string `json:"name"`
	In          string `json:"in"`
	Required    bool   `json:"required"`
	Description string `json:"description"`
	Schema      schema `json:"schema"`
}

type requestBody struct {
	Required bool `json:"required"`
	Content  map[string]struct {
		Schema schema `json:"schema"`
	} `json:"content"`
}

type field struct {
	Name, Flag, In, Kind, Description string
	Enum                              []string
	Required                          bool
}

type operation struct {
	Group, GroupSummary, Name, Summary, Description, Method, Path string
	Params, Body                                                  []field
	HasBody, BodyRequired, BodyJSONOnly, Auth                     bool
	Deprecated                                                    bool
}

// Flags every command already has; a field with one of these names is
// renamed rather than shadowing it.
var reserved = map[string]bool{"token": true, "base-url": true, "output": true, "data": true, "help": true}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: commands <openapi.json> <output.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		fail(fmt.Errorf("parse spec: %w", err))
	}

	var ops []operation
	seen := map[string]string{}
	for path, methods := range doc.Paths {
		for method, rawOp := range methods {
			var op operationDoc
			if err := json.Unmarshal(rawOp, &op); err != nil || op.OperationID == "" {
				continue
			}
			o, err := build(doc, path, strings.ToUpper(method), op)
			if err != nil {
				fail(fmt.Errorf("%s: %w", op.OperationID, err))
			}
			key := o.Group + " " + o.Name
			if prev, dup := seen[key]; dup {
				fail(fmt.Errorf("%s and %s both become `%s`", prev, op.OperationID, key))
			}
			seen[key] = op.OperationID
			ops = append(ops, o)
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].Group != ops[j].Group {
			return ops[i].Group < ops[j].Group
		}
		return ops[i].Name < ops[j].Name
	})

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/gen/commands from the Linkbreakers OpenAPI document %s. DO NOT EDIT.\n\n", doc.Info.Version)
	buf.WriteString("package cli\n\n")
	fmt.Fprintf(&buf, "const specVersion = %q\n\n", doc.Info.Version)
	buf.WriteString("var generatedOperations = []operation{\n")
	for _, o := range ops {
		fmt.Fprintf(&buf, "{Group: %q, GroupSummary: %q, Name: %q, Summary: %q, Description: %q, Method: %q, Path: %q, HasBody: %t, BodyRequired: %t, BodyJSONOnly: %t, Auth: %t, Deprecated: %t,\n",
			o.Group, o.GroupSummary, o.Name, o.Summary, o.Description, o.Method, o.Path, o.HasBody, o.BodyRequired, o.BodyJSONOnly, o.Auth, o.Deprecated)
		writeFields(&buf, "Params", o.Params)
		writeFields(&buf, "Body", o.Body)
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fail(fmt.Errorf("format generated source: %w", err))
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("generated %d commands from spec %s\n", len(ops), doc.Info.Version)
}

func writeFields(buf *bytes.Buffer, name string, fields []field) {
	if len(fields) == 0 {
		return
	}
	fmt.Fprintf(buf, "%s: []field{\n", name)
	for _, f := range fields {
		fmt.Fprintf(buf, "{Name: %q, Flag: %q, In: %q, Kind: %q, Description: %q, Required: %t", f.Name, f.Flag, f.In, f.Kind, f.Description, f.Required)
		if len(f.Enum) > 0 {
			fmt.Fprintf(buf, ", Enum: %#v", f.Enum)
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("},\n")
}

func build(doc document, path, method string, op operationDoc) (operation, error) {
	service, rpc, ok := strings.Cut(op.OperationID, "_")
	if !ok {
		return operation{}, fmt.Errorf("operationId is not Service_Method")
	}
	o := operation{
		Group:        kebab(strings.TrimSuffix(service, "Service")),
		GroupSummary: groupSummary(doc, op.Tags),
		Name:         kebab(rpc),
		Summary:      firstLine(op.Summary),
		Description:  strings.TrimSpace(op.Description),
		Method:       method,
		Path:         path,
		Auth:         len(op.Security) > 0,
		Deprecated:   op.Deprecated,
	}
	if o.Summary == "" {
		o.Summary = firstLine(op.Description)
	}

	used := map[string]bool{}
	flagFor := func(name, in string) string {
		flag := kebab(name)
		if reserved[flag] || used[flag] {
			flag = in + "-" + flag
		}
		used[flag] = true
		return flag
	}

	for _, p := range op.Parameters {
		if p.In != "path" && p.In != "query" && p.In != "header" {
			continue
		}
		kind, enum := kindOf(doc, p.Schema)
		if kind == "json" {
			kind = "string"
		}
		o.Params = append(o.Params, field{
			Name: p.Name, Flag: flagFor(p.Name, p.In), In: p.In, Kind: kind, Enum: enum,
			Description: describeField(doc, p.Description, p.Schema, enum), Required: p.Required || p.In == "path",
		})
	}

	if op.RequestBody != nil {
		content, ok := op.RequestBody.Content["application/json"]
		if ok {
			o.HasBody = true
			o.BodyRequired = op.RequestBody.Required
			body := resolve(doc, content.Schema)
			if len(body.Properties) == 0 {
				o.BodyJSONOnly = true
			}
			names := make([]string, 0, len(body.Properties))
			for name := range body.Properties {
				names = append(names, name)
			}
			sort.Strings(names)
			for _, name := range names {
				prop := body.Properties[name]
				kind, enum := kindOf(doc, prop)
				o.Body = append(o.Body, field{
					Name: name, Flag: flagFor(name, "body"), In: "body", Kind: kind, Enum: enum,
					Description: describeField(doc, prop.Description, prop, enum), Required: contains(body.Required, name),
				})
			}
		}
	}
	return o, nil
}

// groupSummary is the first sentence of the operation's tag description.
func groupSummary(doc document, tags []string) string {
	for _, tag := range doc.Tags {
		if len(tags) > 0 && tag.Name == tags[0] {
			text := strings.Join(strings.Fields(tag.Description), " ")
			if i := strings.Index(text, ". "); i >= 0 {
				text = text[:i]
			}
			return strings.TrimSuffix(text, ".")
		}
	}
	return ""
}

func resolve(doc document, s schema) schema {
	for s.Ref != "" {
		name := s.Ref[strings.LastIndex(s.Ref, "/")+1:]
		next, ok := doc.Components.Schemas[name]
		if !ok {
			return schema{}
		}
		if s.Description != "" && next.Description == "" {
			next.Description = s.Description
		}
		if s.Title != "" && next.Title == "" {
			next.Title = s.Title
		}
		s = next
	}
	if len(s.AllOf) == 1 {
		return resolve(doc, s.AllOf[0])
	}
	return s
}

// kindOf is how a value is read from the command line: a scalar flag, a
// repeatable string flag, or a JSON value for anything with structure.
func kindOf(doc document, s schema) (string, []string) {
	s = resolve(doc, s)
	if len(s.Enum) > 0 {
		values := make([]string, 0, len(s.Enum))
		for _, v := range s.Enum {
			values = append(values, fmt.Sprint(v))
		}
		return "string", values
	}
	switch typeName(s.Type) {
	case "boolean":
		return "boolean", nil
	case "integer":
		return "integer", nil
	case "number":
		return "number", nil
	case "string":
		return "string", nil
	case "array":
		if s.Items != nil {
			item, enum := kindOf(doc, *s.Items)
			if item == "string" {
				return "strings", enum
			}
		}
		return "json", nil
	default:
		return "json", nil
	}
}

func typeName(raw json.RawMessage) string {
	if len(raw) == 0 {
		return ""
	}
	var single string
	if json.Unmarshal(raw, &single) == nil {
		return single
	}
	var many []string
	if json.Unmarshal(raw, &many) == nil {
		for _, t := range many {
			if t != "null" {
				return t
			}
		}
	}
	return ""
}

// describeField drops grpc-gateway's per-value enum documentation, "- A: ...
// - B: ...", which the flag already lists as its accepted values.
func describeField(doc document, text string, s schema, enum []string) string {
	desc := describe(text, s)
	if len(enum) > 0 && strings.HasPrefix(desc, "- ") {
		return ""
	}
	return desc
}

func describe(text string, s schema) string {
	text = strings.TrimSpace(text)
	if text == "" {
		text = strings.TrimSpace(s.Description)
	}
	if text == "" {
		text = strings.TrimSpace(s.Title)
	}
	return strings.Join(strings.Fields(firstParagraph(text)), " ")
}

func firstParagraph(text string) string {
	if i := strings.Index(text, "\n\n"); i >= 0 {
		return text[:i]
	}
	return text
}

func firstLine(text string) string {
	text = strings.TrimSpace(text)
	if i := strings.IndexByte(text, '\n'); i >= 0 {
		text = text[:i]
	}
	return strings.TrimSuffix(text, ".")
}

// kebab turns CamelCase and camelCase into kebab-case, keeping acronyms
// together: ResolveQrcodeImages -> resolve-qrcode-images, GetMCPServer ->
// get-mcp-server, Idempotency-Key -> idempotency-key.
func kebab(s string) string {
	runes := []rune(s)
	var out []rune
	for i, r := range runes {
		if r == '_' || r == '-' || r == ' ' || r == '.' {
			if len(out) > 0 && out[len(out)-1] != '-' {
				out = append(out, '-')
			}
			continue
		}
		if unicode.IsUpper(r) {
			prevLower := i > 0 && (unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1]))
			nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			prevUpper := i > 0 && unicode.IsUpper(runes[i-1])
			if len(out) > 0 && out[len(out)-1] != '-' && (prevLower || (prevUpper && nextLower)) {
				out = append(out, '-')
			}
			out = append(out, unicode.ToLower(r))
			continue
		}
		out = append(out, r)
	}
	return strings.Trim(string(out), "-")
}

func contains(list []string, v string) bool {
	for _, item := range list {
		if item == v {
			return true
		}
	}
	return false
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
